#!/usr/bin/env bash
# Regenera el modelo compilado y las consultas precompiladas de la base del cascarón (P5) en
# src/FrameworkConcept.Shell/Data/Compilado/. Corre .NET dentro del contenedor, con scripts/contenedor.sh.
#
#   scripts/modelo-compilado.sh
#
# Cuándo: cada vez que cambian Data/ContextoDelCascaron.cs, Data/Tablas.cs o Data/DbSqlite.cs (aunque sea un
# comentario: los interceptores apuntan a línea y columna de cada consulta, y si se corren, el cascarón no compila).
# El resultado se versiona. README.md, «La base del cascarón sin código dinámico», cuenta por qué existe.
#
# Qué hace:
#   1. restaura dotnet-ef como herramienta LOCAL (.config/dotnet-tools.json; la versión es la de EF Core de
#      Directory.Build.props y cambian juntas);
#   2. corre «dotnet ef dbcontext optimize --precompile-queries --nativeaot» sobre el proyecto de diseño
#      tools/FrameworkConcept.Shell.Diseno, que enlaza los archivos de datos del cascarón (el cascarón es MAUI y la
#      herramienta no puede cargarlo);
#   3. saca con «dotnet ef dbcontext script» el SQL que crea la base y lo deja como constante en
#      Data/Compilado/SqlDeCreacion.cs (EnsureCreated necesita el modelo de diseño, que sin código dinámico no carga);
#   4. corrige dos cosas de la salida de EF 10.0.11, que es experimental (EF9100):
#      - la ruta de los [InterceptsLocation]: EF la escribe absoluta (la del contenedor, /work/…), y así el cascarón
#        sólo compilaría en una máquina con esa misma carpeta. Queda relativa al archivo del interceptor;
#      - el nombre de una variable de las consultas sin seguimiento (AsNoTracking): EF lo arma con el nombre completo
#        del tipo, con puntos («var frameworkConcept.Shell.Data.FilaDeOutboxPrimaryKeyProperties»), y no compila.
#        Se le sacan el espacio de nombres;
#      - la llamada a IInjectableService sobre cada fila recién leída: EF convierte la fila directo a la interfaz, y
#        con una clase sellada (las de Tablas.cs lo son) eso no compila (CS0030). Se convierte pasando por object;
#      - los avisos que deja el código generado (la forma vieja de InterceptsLocation, CS9270; anotaciones de nulos
#        fuera de #nullable, CS8669; API obsoleta, CS0618), que con avisos como error (CI) frenarían la compilación.
set -euo pipefail

DEMO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SALIDA=src/FrameworkConcept.Shell/Data/Compilado

rm -rf "${DEMO:?}/$SALIDA"
"$DEMO/scripts/contenedor.sh" bash -c "
  set -euo pipefail
  dotnet tool restore >/dev/null
  cd tools/FrameworkConcept.Shell.Diseno
  dotnet ef dbcontext optimize --precompile-queries --nativeaot \
    -o ../../$SALIDA -n FrameworkConcept.Shell.Data.Compilado
  dotnet ef dbcontext script --no-build -o ../../$SALIDA/creacion.sql"

# Los interceptores viven en Data/Compilado/; DbSqlite.cs, un nivel arriba.
sed -i -E \
  -e 's#InterceptsLocation\(@"[^"]*/src/FrameworkConcept\.Shell/Data/DbSqlite\.cs"#InterceptsLocation(@"../DbSqlite.cs"#' \
  -e 's#frameworkConcept\.Shell\.Data\.([A-Za-z]+PrimaryKeyProperties)#\1#g' \
  -e 's#\(\(IInjectableService\)([A-Za-z0-9_]+)\)#((IInjectableService)(object)\1)#g' \
  -e 's#if \(([A-Za-z0-9_]+) is IInjectableService\)#if ((object)\1 is IInjectableService)#g' \
  -e 's#^\#pragma warning disable EF9100.*#&\n\#pragma warning disable CS9270, CS8669, CS0618 // código generado por EF: ver scripts/modelo-compilado.sh#' \
  "$DEMO/$SALIDA"/DbSqlite.EFInterceptors.*.cs

# El script, como cadena literal cruda de C# (sin escapes: el SQL no trae comillas triples).
{
  echo '// <auto-generated /> por scripts/modelo-compilado.sh, con «dotnet ef dbcontext script». No editar a mano.'
  echo 'namespace FrameworkConcept.Shell.Data.Compilado;'
  echo
  echo '/// <summary>P5 — El SQL que crea la base del cascarón, el mismo que correría EnsureCreated.</summary>'
  echo 'public static class SqlDeCreacion'
  echo '{'
  echo '    public const string Script = """'
  tr -d '\r' < "$DEMO/$SALIDA/creacion.sql" | sed -e '1s/^\xEF\xBB\xBF//' -e '/^$/d' -e 's/^/        /'
  echo '        """;'
  echo '}'
} > "$DEMO/$SALIDA/SqlDeCreacion.cs"
rm "$DEMO/$SALIDA/creacion.sql"

if grep -n 'InterceptsLocation(@"/' "$DEMO/$SALIDA"/*.cs; then
  echo "modelo-compilado: quedó una ruta absoluta en un interceptor (arriba)" >&2
  exit 1
fi
echo "modelo-compilado: listo en $SALIDA ($(grep -c 'InterceptsLocation' "$DEMO/$SALIDA"/DbSqlite.EFInterceptors.*.cs) llamadas interceptadas)"
